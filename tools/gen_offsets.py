"""Derive source/warpforge_offsets.h from the game's own libunity.so.

Usage: python tools/gen_offsets.py path/to/libunity.so > source/warpforge_offsets.h

The addresses below were found by hand (see the notes in the generated header):
CloverPit's fingerprints (same Unity 6000.2.6f2) matched three of them directly, and
ChoreographerBase::Get / WaitVSync were confirmed by disassembly. This script turns
each site into a masked 16-word fingerprint in cloverpit_locate.c's scheme (branch,
adrp/adr, cbz/tbz and literal-load operands masked; the add that completes an adrp
and sp frame adjustments masked to their shape), checks every fingerprint matches
exactly once in the binary, and prints the header. Re-run it against a new game
build: if a site moved but the code shape held, the scan still finds it.
"""
import struct
import sys

# Virtual addresses in Warpforge 1.35.0's libunity.so (BuildID 1b3a1bcc1de96da2).
TARGETS = [
    # name, define suffix, vaddr, reference (CloverPit 1.4.8) rva, note
    ("TimeManager::Update(double)", "TM_UPDATE", 0x733530, 0x649e4c,
     "entry bumps frameCount/renderCount, checks the pause byte, body at +0x24"),
    ("ChoreographerBase::Get()", "CHOREO_GET", 0x9085c4, 0x7ff308,
     "the function that logs 'NDK Choreographer requires device API Level'"),
    ("AndroidAudio::GetAndroidAudioOutputType(int)", "AUDIO_OUTTYPE", 0x918b3c, 0x80f880,
     "16-word fingerprint from CloverPit matched here exactly once"),
    ("FMOD OpenSL buffer geometry", "FMOD_BUFGEOM", 0x13a1a68, 0x11a3494,
     "the `sub w10, w20, #1` run; -8/-4/+0x1c/+0x78 words verified against the guards"),
]
FP_WORDS = {"TM_UPDATE": 16, "CHOREO_GET": 16, "AUDIO_OUTTYPE": 16, "FMOD_BUFGEOM": 8}

WAITVSYNC_ADRP = 0x9083f4   # adrp x20, #0x1807000 -- the mutex
WAITVSYNC_LDR = 0x90840c    # ldr x21, [x22, #0x5e0] -- the counter load
VSYNC_COUNTER = 0x18075e0   # .bss, uint64 (0x1807000 + 0x5e0)


def load(path):
    d = open(path, "rb").read()
    # program headers: find the executable PT_LOAD to map vaddr <-> file offset
    e_phoff, = struct.unpack_from("<Q", d, 0x20)
    e_phentsize, e_phnum = struct.unpack_from("<HH", d, 0x36)
    segs = []
    for i in range(e_phnum):
        p_type, p_flags, p_offset, p_vaddr, _, p_filesz = struct.unpack_from(
            "<IIQQQQ", d, e_phoff + i * e_phentsize)
        if p_type == 1:
            segs.append((p_vaddr, p_offset, p_filesz, p_flags))
    return d, segs


def v2f(segs, va):
    for vaddr, off, sz, _ in segs:
        if vaddr <= va < vaddr + sz:
            return va - vaddr + off
    raise ValueError(hex(va))


def mask_for(w, prev):
    top8 = w >> 24
    if (w & 0xFC000000) in (0x14000000, 0x94000000):          # B / BL
        return 0xFC000000
    if top8 == 0x54:                                          # B.cond
        return 0xFF00001F
    if top8 in (0x34, 0x35, 0xB4, 0xB5):                      # CBZ / CBNZ
        return 0xFF00001F
    if top8 in (0x36, 0x37, 0xB6, 0xB7):                      # TBZ / TBNZ
        return 0xFF00001F
    if (w & 0x9F000000) in (0x90000000, 0x10000000):          # ADRP / ADR
        return 0x9F00001F
    if (w & 0xBF000000) == 0x18000000 or top8 == 0x58:        # LDR literal
        return 0xFF00001F
    if (w & 0xFF8003E0) == 0x910003E0 or (w & 0xFF8003E0) == 0xD10003E0:  # add/sub sp
        if (w & 0x1F) == 0x1F or ((w >> 5) & 0x1F) == 0x1F:
            return 0xFFC003FF
    if (w & 0xFF800000) == 0x91000000 and prev is not None:   # add completing an adrp
        if (prev & 0x9F000000) == 0x90000000 and ((w >> 5) & 0x1F) == (prev & 0x1F):
            return 0xFFC003FF
    return 0xFFFFFFFF


def fingerprint(d, segs, va, n):
    off = v2f(segs, va)
    words = struct.unpack_from("<%dI" % n, d, off)
    fp = []
    prev = None
    for w in words:
        m = mask_for(w, prev)
        fp.append((w, m))
        prev = w
    return fp


def scan(d, segs, fp):
    hits = []
    for vaddr, off, sz, flags in segs:
        if not (flags & 1):
            continue
        words = struct.unpack_from("<%dI" % (sz // 4), d, off)
        n = len(fp)
        p0, m0 = fp[0]
        for i in range(len(words) - n):
            if words[i] & m0 != p0 & m0:
                continue
            if all((words[i + k] & fp[k][1]) == (fp[k][0] & fp[k][1]) for k in range(n)):
                hits.append(vaddr + i * 4)
    return hits


def word(d, segs, va):
    return struct.unpack_from("<I", d, v2f(segs, va))[0]


def main():
    d, segs = load(sys.argv[1])
    out = []
    out.append("/* warpforge_offsets.h -- Unity 6000.2.6f2 engine internals for Warpforge 1.35.0.")
    out.append(" * GENERATED by tools/gen_offsets.py from the game's own libunity.so")
    out.append(" * (24,639,856 bytes, BuildID 1b3a1bcc1de96da2). Do not edit by hand.")
    out.append(" *")
    out.append(" * Same scheme as cloverpit_offsets.h (same engine version): every site carries a")
    out.append(" * masked fingerprint for the runtime scan (tier 1) and the measured address plus")
    out.append(" * its first word as a guard (tier 2). Struct field offsets are version-invariant")
    out.append(" * and were re-read off this binary's TimeManager::Update prologue. */")
    out.append("#ifndef CLOVERPIT_OFFSETS_H")
    out.append("#define CLOVERPIT_OFFSETS_H")
    out.append("#include <stdint.h>")
    out.append("typedef struct { uint32_t pattern, mask; } fp_word;")
    out.append("typedef struct {")
    out.append("    const char    *name;")
    out.append("    const fp_word *fp;")
    out.append("    int            n;")
    out.append("    uint32_t       game_rva;   /* verified for Warpforge 1.35.0 */")
    out.append("    uint32_t       guard;      /* first word at game_rva, exact */")
    out.append("    uint32_t       ref_rva;    /* provenance only (CloverPit 1.4.8) */")
    out.append("} fp_target;")
    out.append("")
    for name, suf, va, ref, note in TARGETS:
        n = FP_WORDS[suf]
        fp = fingerprint(d, segs, va, n)
        hits = scan(d, segs, fp)
        if hits != [va]:
            sys.exit("fingerprint %s matches %s, want [%s]" % (suf, [hex(h) for h in hits], hex(va)))
        exact = sum(1 for _, m in fp if m == 0xFFFFFFFF)
        out.append("/* %s\n * game 0x%x  (reference 0x%x)  %d words, %d exact -- %s */" % (name, va, ref, n, exact, note))
        out.append("static const fp_word FP_%s[] = {" % suf)
        for w, m in fp:
            out.append("    { 0x%08x, 0x%08x }," % (w, m))
        out.append("};")
        out.append("#define FP_%s_N        %d" % (suf, n))
        out.append("#define GAME_RVA_%s    0x%xu" % (suf, va))
        out.append("#define GUARD_%s       0x%08xu" % (suf, fp[0][0]))
        out.append("#define REF_RVA_%s     0x%xu" % (suf, ref))
        out.append("")
    # TimeManager fields: checked against the prologue
    w = [word(d, segs, 0x733530 + 4 * i) for i in range(3)]
    assert w == [0xf940b008, 0xb9416809, 0x3946a00a], [hex(x) for x in w]
    out.append("/* TimeManager fields, read off this binary's TimeManager::Update prologue:")
    out.append(" *   ldr x8,[x0,#0x160] / ldr w9,[x0,#0x168] / ldrb w10,[x0,#0x1a8] */")
    out.append("#define TM_FIELD_FRAMECOUNT   0x160   /* u64 */")
    out.append("#define TM_FIELD_RENDERCOUNT  0x168   /* u32 */")
    out.append("#define TM_FIELD_PAUSE        0x1a8   /* u8  */")
    assert word(d, segs, 0x733530 + 0x24) == 0xd10243ff
    out.append("/* body (own frame, directly callable) at entry + 0x24: `sub sp, sp, #0x90` */")
    out.append("#define TM_BODY_DELTA         0x24")
    out.append("")
    out.append("#define AUDIO_SELECT_OPENSL   2")
    out.append("#define PATCH_RET_OPENSL      { 0x52800040u, 0xd65f03c0u }   /* mov w0,#2 ; ret */")
    out.append("#define PATCH_RET_NULL        { 0xd2800000u, 0xd65f03c0u }   /* mov x0,#0 ; ret */")
    out.append("")
    # FMOD secondary words
    base = 0x13a1a68
    chk = {-8: 0xb943fa69, -4: 0x34000129, 0x1c: 0x54000089, 0x78: 0x1ac90949}
    for o, want in chk.items():
        got = word(d, segs, base + o)
        assert got == want, (hex(o), hex(got))
    out.append("/* FMOD OpenSL buffer geometry: every secondary word verified on this binary. */")
    out.append("#define FMOD_BUFGEOM_BRANCH_OFF  0x1cu")
    out.append("#define FMOD_PERIOD_LDR_OFF      (-8)")
    out.append("#define FMOD_PERIOD_CBZ_OFF      (-4)")
    out.append("#define GUARD_FMOD_PERIOD_LDR    0xb943fa69u  /* ldr w9,[x19,#0x3f8] */")
    out.append("#define GUARD_FMOD_PERIOD_CBZ    0x34000129u  /* cbz w9, fail        */")
    out.append("#define PATCH_FMOD_PERIOD_MOV    (0x52800000u | ((CP_AUDIO_PERIOD_FRAMES & 0xffffu) << 5) | 9u)")
    out.append("#define PATCH_FMOD_PERIOD_STR    0xb903fa69u  /* str w9,[x19,#0x3f8] */")
    out.append("#define FMOD_BUFCOUNT_OFF        0x78u")
    out.append("#define GUARD_FMOD_BUFCOUNT      0x1ac90949u  /* udiv w9, w10, w9 */")
    out.append("#define PATCH_FMOD_BUFCOUNT      (0x52800000u | ((CP_AUDIO_UPFRONT_BUFFERS & 0xffffu) << 5) | 9u)")
    out.append("#define GUARD_FMOD_BUFGEOM_BLS   0x54000089u  /* b.ls +0x10 */")
    out.append("#define PATCH_FMOD_BUFGEOM_B     0x14000004u  /* b    +0x10 -- same target  */")
    out.append("")
    out.append("static const fp_target CLOVERPIT_TARGETS[] = {")
    for name, suf, va, ref, note in TARGETS:
        out.append("    { \"%s\", FP_%s, FP_%s_N, GAME_RVA_%s, GUARD_%s, REF_RVA_%s }," % (name.split("(")[0], suf, suf, suf, suf, suf))
    out.append("};")
    out.append("#define CLOVERPIT_TARGETS_N (sizeof(CLOVERPIT_TARGETS)/sizeof(CLOVERPIT_TARGETS[0]))")
    out.append("")
    wa, wl = word(d, segs, WAITVSYNC_ADRP), word(d, segs, WAITVSYNC_LDR)
    assert wa == 0xf00077f4 and wl == 0xf942f2d5, (hex(wa), hex(wl))
    out.append("/* Android vsync counter. WaitVSync(long) at 0x9083e8 blocks on")
    out.append(" *   mutex 0x1807584 / counter 0x18075e0 (.bss) until counter >= target;")
    out.append(" * the Choreographer callback that bumps it (0x908450) never runs here, so the")
    out.append(" * clock thread bumps it at ~60 Hz. Two guard words: the adrp forming the mutex")
    out.append(" * and the ldr the counter offset was decoded from. */")
    out.append("#define GAME_RVA_WaitVSync        0x%xu   /* adrp x20, #0x1807000 */" % WAITVSYNC_ADRP)
    out.append("#define GUARD_WaitVSync           0x%08xu" % wa)
    out.append("#define GAME_RVA_WaitVSync_ldr    0x%xu   /* ldr x21, [x22, #0x5e0] */" % WAITVSYNC_LDR)
    out.append("#define GUARD_WaitVSync_ldr       0x%08xu" % wl)
    out.append("#define GAME_RVA_VSYNC_COUNTER    0x%xu   /* .bss, uint64 */" % VSYNC_COUNTER)
    out.append("#define VSYNC_PERIOD_NS           16666667ull  /* ~60 Hz */")
    out.append("")
    out.append("#endif /* CLOVERPIT_OFFSETS_H */")
    print("\n".join(out))


if __name__ == "__main__":
    main()
